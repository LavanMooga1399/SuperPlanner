"""Extraction corpus for the rule-based reader (PHASE2 2.7): realistic Indian-English and plain-English texts.

Every expectation is written from the grammar in PHASE2 2.7 (not from the reader's output). `today` is
2026-10-17 (a Saturday), so "next Monday" = 2026-10-19, "tomorrow" = 2026-10-18, "end of next month" =
2026-11-30, "within 3 weeks" = 2026-11-07, "next year" (finance) = start + 12 months = 2027-10.

Schedule task expectations (only the listed fields are scored):
    duration: (optimistic, likely, pessimistic, unit)  - compared in minutes with 1 d = 480, 1 w = 2400
    after:    names of predecessor tasks (set)
    resources: names of assigned resources (set)
    milestone, deadline ("YYYY-MM-DD"), deadline_hard
Finance item expectations are matched by collection and kind/name and score the listed fields.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class SCase:
    id: str
    text: str
    tasks: dict[str, dict[str, Any]] = field(default_factory=dict)
    resources: dict[str, int] = field(default_factory=dict)          # name -> count
    top: dict[str, Any] = field(default_factory=dict)                # kind, start_date, n_tasks, days, windows
    locale: str = "en-IN"
    kind: str | None = None


@dataclass
class FCase:
    id: str
    text: str
    items: list[tuple[str, dict[str, Any]]] = field(default_factory=list)   # (collection, fields)
    profile: dict[str, Any] = field(default_factory=dict)
